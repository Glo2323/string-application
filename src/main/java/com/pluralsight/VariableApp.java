package com.pluralsight;


public class VariableApp {

    public static void main(String[] args) {
        //Declare a variable to store your favorite color
        String favoriteColor = "red";
        System.out.println(favoriteColor);

        //Declare a variable to store the year you started this class
        int  yearStartedClass = 2026;
        System.out.println(yearStartedClass);

        //Declare a variable to store your middle initial
        char middleInitial = 'S';
        System.out.println(middleInitial);

        //Declare a variable to store whether you have pets (yes/no)
        boolean havepets = false;
        System.out.println(havepets);

        //Declare a variable with a nice message or saying
        String message = "You look good today";
        System.out.println(message);

        // The number of days in a week
        int daysOfTheWeek = 7;
        System.out.println("The number of days in a week is " + daysOfTheWeek);

        //The price of coffee
        double priceOfCoffee = 4.99;
        System.out.println("The coffee at the store cost " + priceOfCoffee);

        //Your favorite letter
        char favoriteLetter = 'M';
        System.out.println("Did you know my favorite letter was " + favoriteLetter);

        //Whether it's raining
        boolean isItRaining = false;
        System.out.println("Is it raining outside " + isItRaining );

    }



}
